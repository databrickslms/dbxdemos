-- ============================================================================
-- fct_aum_legacy  —  the previous AUM extract
-- Superseded by fct_aum_snapshot but never retired. Its totals disagree,
-- because it was built before discretionary and advisory were reported apart.
-- ============================================================================
CREATE OR REPLACE TABLE {{STAGING}}fct_aum_legacy
COMMENT 'Legacy AUM extract. Superseded by fct_aum_snapshot.'
AS
SELECT
  s.account_id,
  s.snapshot_date                                       AS report_date,
  -- The legacy extract added held-away assets into a single total.
  cast(s.market_value_local + s.held_away_value_local AS DECIMAL(18,2)) AS aum,
  s.local_currency                                      AS currency
FROM {{CORE}}fct_aum_snapshot s
WHERE s.snapshot_date = last_day(s.snapshot_date)
  AND s.snapshot_date < DATE'2025-10-01';


