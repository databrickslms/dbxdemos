  SET TAGS ('deprecated' = 'true', 'superseded_by' = 'fct_aum_snapshot');

ALTER TABLE {{STAGING}}fct_holdings_raw
  SET TAGS ('deprecated' = 'true', 'note' = 'raw custodian feed, not for reporting');


